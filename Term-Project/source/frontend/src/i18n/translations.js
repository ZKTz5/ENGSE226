export function translate(language, key, values = {}) {
  const template = translations[language]?.[key] ?? translations.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
}

export function displayCampusName(name, language) {
  if (name === 'Jed Yod') return translate(language, 'campus.jedYod');
  if (name === 'Doi Saket') return translate(language, 'campus.doiSaket');
  return name;
}

export function formatDeparture(value, language) {
  const parsed = value instanceof Date ? value : new Date(String(value).replace(' ', 'T'));
  if (Number.isNaN(parsed.getTime())) return String(value ?? '');
  return new Intl.DateTimeFormat(language === 'th' ? 'th-TH' : 'en-US', {
    weekday: 'short', year: 'numeric', month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit',
  }).format(parsed);
}

