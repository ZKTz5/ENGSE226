export function translate(language, key, values = {}) {
  const template = translations[language]?.[key] ?? translations.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
}

export function displayCampusName(name, language) {
  if (name === 'Jed Yod') return translate(language, 'campus.jedYod');
  if (name === 'Doi Saket') return translate(language, 'campus.doiSaket');
  return name;
}

export function formatDeparture(value, language) {
  const parsed = new Date(String(value).replace(' ', 'T'));
  if (Number.isNaN(parsed.getTime())) return value;
  return new Intl.DateTimeFormat(language === 'th' ? 'th-TH' : 'en-US', {
    weekday: 'short', year: 'numeric', month: 'short', day: 'numeric',
    hour: '2-digit', minute: '2-digit',
  }).format(parsed);
}

const API_ERROR_KEYS = {
  invalid_email_domain: 'login.invalidDomain',
  invalid_credentials: 'login.invalidCredentials',
  invalid_login_input: 'login.required',
  expired_schedule: 'api.expired',
  duplicate_booking: 'api.duplicate',
  forbidden: 'api.forbidden',
  already_cancelled: 'api.alreadyCancelled',
  invalid_schedule_filters: 'api.invalidFilters',
  schedule_not_found: 'api.notFound',
  booking_not_found: 'api.notFound',
  missing_schedule_id: 'api.invalidFilters',
  authentication_required: 'api.authRequired',
  invalid_token: 'api.authRequired',
};

export function apiErrorKey(error) {
  if (API_ERROR_KEYS[error?.code]) return API_ERROR_KEYS[error.code];
  if (error?.status === 0) return 'state.networkError';
  if (error?.status === 404) return 'api.notFound';
  return 'api.generic';
}
