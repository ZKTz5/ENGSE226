export function apiErrorKey(error) {
  if (API_ERROR_KEYS[error?.code]) return API_ERROR_KEYS[error.code];
  if (error?.status === 0) return 'state.networkError';
  if (error?.status === 404) return 'api.notFound';
  return 'api.generic';
}
